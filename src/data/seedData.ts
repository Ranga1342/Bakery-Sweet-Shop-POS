function buildPermissions(overrides: Partial<Record<NavSection, ModulePermissionSet>>): Record<NavSection, ModulePermissionSet> {
  return {
    dashboard: overrides.dashboard ?? VIEW_ONLY,
    pos: overrides.pos ?? NONE,
    menus: overrides.menus ?? NONE,
    custom_orders: overrides.custom_orders ?? NONE,
    stock: overrides.stock ?? NONE,
    inventory: overrides.inventory ?? NONE,
    customers: overrides.customers ?? NONE,
    reports: overrides.reports ?? NONE,
    staff: overrides.staff ?? NONE,
    branches: overrides.branches ?? NONE,
    settings: overrides.settings ?? NONE,
  };
}

